/// The 8 rows of an 8x8 cell for `c` (unknown characters show as '?').
/// Bit 7 is the leftmost pixel.
pub fn glyph(c: char) -> [u8; 8] {
    if c == '\u{4}' {
        // The diamond used for the gems (our own drawing).
        return [0x10, 0x38, 0x7C, 0xFE, 0x7C, 0x38, 0x10, 0x00];
    }
    let i = match c as u32 {
        0x20..=0x7E => c as usize - 0x20,
        _ => '?' as usize - 0x20,
    };
    let mut out = [0u8; 8];
    for (r, &bits) in GLYPHS[i].iter().enumerate() {
        let b = bits << 2; // 5 columns placed at 1..=5 of the cell
        out[r] = b | (b >> 1); // embolden: columns 1..=6
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn space_is_blank_and_letters_are_not() {
        assert_eq!(glyph(' '), [0; 8]);
        assert!(glyph('A').iter().any(|&r| r != 0));
        assert_eq!(glyph('\u{1}'), glyph('?'));
        // Nothing spills into the rightmost column or the bottom row.
        for c in (0x20u8..0x7F).map(char::from) {
            let g = glyph(c);
            assert_eq!(g[7], 0);
            assert!(g.iter().all(|&r| r & 1 == 0));
        }
    }
}
